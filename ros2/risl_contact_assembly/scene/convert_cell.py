"""Convert the lab's Vention workstation USD into the MuJoCo cell scene.

Run in an environment with ``usd-core`` (it is not a ROS dependency)::

    python convert_cell.py vention.usd cell.xml

Every top-level part of the Vention assembly becomes one box: its
axis-aligned bounding box. The frame is built from orthogonal extrusions and
plates, so the boxes are tight; curved or hollow sub-assemblies are
overestimated, which is the safe direction for a clearance check. No mesh is
written, because the Vention export is not redistributable.

Frame: the UR controller ``base`` frame, metres. The robot stands on the
plate named ``*robo_base2``; ``base`` has its origin at the centre of that
plate's top face and its axes parallel to the USD axes. This is the placement
used by the lab's Isaac twin, which loads the robot yawed pi so that its world
frame is ``base``.
"""

from hashlib import sha256
from pathlib import Path
from sys import argv

from pxr import Usd, UsdGeom

ASSEMBLY_PREFIX = "VentionAssembly"
ROBOT_PLATE = "robo_base2"
# Parts that ride the linear axis with the robot; the rest is the bench.
CARRIAGE_PARTS = ("robo_base1", "robo_base2")
MIN_HALF_SIZE_M = 0.0005
PART_COLORS = (
    ("PANEL", "0.72 0.6 0.45 1"),
    ("robo_base", "0.3 0.3 0.32 1"),
    ("ST_EXT", "0.16 0.42 0.72 1"),
    ("", "0.45 0.47 0.5 1"),
)


def main(usd_file: str, cell_file: str) -> None:
    """Write the cell MJCF for a workstation USD.

    Args:
        usd_file: Vention workstation USD (``workstation/vention.usd``).
        cell_file: MJCF file to write.
    """
    stage = Usd.Stage.Open(usd_file)
    metres = UsdGeom.GetStageMetersPerUnit(stage)
    (assembly,) = (
        prim
        for prim in stage.GetDefaultPrim().GetChildren()
        if prim.GetName().startswith(ASSEMBLY_PREFIX)
    )
    bounds = UsdGeom.BBoxCache(
        Usd.TimeCode.Default(), [UsdGeom.Tokens.default_, UsdGeom.Tokens.render]
    )
    boxes = {}
    for part in assembly.GetChildren():
        box = bounds.ComputeWorldBound(part).ComputeAlignedRange()
        if not box.IsEmpty():
            boxes[part.GetName()] = (
                [value * metres for value in box.GetMin()],
                [value * metres for value in box.GetMax()],
            )
    (plate,) = (name for name in boxes if ROBOT_PLATE in name)
    plate_min, plate_max = boxes[plate]
    origin = [
        (plate_min[0] + plate_max[0]) / 2,
        (plate_min[1] + plate_max[1]) / 2,
        plate_max[2],
    ]

    geoms = {"carriage": [], "bench": []}
    for name, (low, high) in sorted(boxes.items()):
        centre = " ".join(
            f"{(low[axis] + high[axis]) / 2 - origin[axis]:.4f}" for axis in range(3)
        )
        half_size = " ".join(
            f"{max((high[axis] - low[axis]) / 2, MIN_HALF_SIZE_M):.4f}"
            for axis in range(3)
        )
        color = next(rgba for key, rgba in PART_COLORS if key in name)
        body = "carriage" if any(key in name for key in CARRIAGE_PARTS) else "bench"
        geoms[body].append(
            f'      <geom name="{name}" type="box" pos="{centre}" '
            f'size="{half_size}" rgba="{color}"/>'
        )
    floor_z = min(low[2] for low, _ in boxes.values()) - origin[2]
    digest = sha256(Path(usd_file).read_bytes()).hexdigest()
    Path(cell_file).write_text(
        "\n".join(
            [
                "<!-- Generated by convert_cell.py; do not edit.",
                f"     Source: {Path(usd_file).name}, sha256 {digest}.",
                "     Frame: UR base, metres. One box per Vention part. -->",
                '<mujoco model="cell">',
                "  <worldbody>",
                f'    <geom name="floor" type="plane" pos="0 0 {floor_z:.4f}" '
                'size="3 3 0.1" rgba="0.82 0.82 0.8 1"/>',
                '    <body name="carriage">',
                *geoms["carriage"],
                "    </body>",
                '    <body name="bench">',
                *geoms["bench"],
                "    </body>",
                "  </worldbody>",
                "</mujoco>",
                "",
            ]
        ),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main(argv[1], argv[2])
